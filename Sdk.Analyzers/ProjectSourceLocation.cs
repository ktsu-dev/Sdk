namespace ktsu.Sdk.Analyzers;

using System;
using System.IO;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

/// <summary>
/// Picks a location for a project-level diagnostic that the project itself owns.
/// </summary>
/// <remarks>
/// Simply taking the compilation's first syntax tree is wrong. Package compile items are prepended
/// to the compilation, so with a source-embedding package such as Polyfill the first tree is a file
/// from that package, carrying an <c>auto-generated</c> header. Diagnostics located in generated
/// code are dropped under <see cref="GeneratedCodeAnalysisFlags.None"/>, which silently loses the
/// diagnostic - the root cause of ktsu-dev/Sdk#12 / #8 / #11. Restricting the choice to files under
/// the project directory, excluding the intermediate output, also guarantees that any accompanying
/// code fix edits a file the user actually owns rather than one in the NuGet cache.
/// <para>
/// A project can own generated files too, such as a resx designer at
/// <c>Properties/Resources.Designer.cs</c>, and MSBuild lists subfolder files before root files, so
/// those are skipped the same way (ktsu-dev/Sdk#111). A generated tree is chosen only when the
/// project has nothing else.
/// </para>
/// </remarks>
internal static class ProjectSourceLocation
{
	/// <summary>
	/// Finds a location in a source file the project owns.
	/// </summary>
	/// <param name="compilation">The compilation being analyzed.</param>
	/// <param name="optionsProvider">
	/// The analyzer config options, used to read <c>ProjectDir</c> and each file's <c>generated_code</c>.
	/// </param>
	/// <returns>A location in a project-owned file, or <see cref="Location.None"/> when there is none.</returns>
	public static Location Find(Compilation compilation, AnalyzerConfigOptionsProvider optionsProvider)
	{
		optionsProvider.GlobalOptions.TryGetValue("build_property.ProjectDir", out string? projectDir);

		SyntaxTree[] owned = string.IsNullOrEmpty(projectDir)
			? []
			: [.. compilation.SyntaxTrees.Where(t => IsProjectOwned(t.FilePath, projectDir!))];

		SyntaxTree? tree = owned.FirstOrDefault(t => !IsGenerated(t, optionsProvider))
			?? owned.FirstOrDefault()
			?? compilation.SyntaxTrees.FirstOrDefault();

		return tree?.GetRoot().GetLocation() ?? Location.None;
	}

	/// <summary>
	/// Determines whether the compiler treats a file as generated code, and so drops diagnostics in it
	/// under <see cref="GeneratedCodeAnalysisFlags.None"/>.
	/// </summary>
	/// <remarks>
	/// Mirrors Roslyn's rules: a <c>generated_code</c> setting decides when present; otherwise the file
	/// name or an <c>&lt;auto-generated</c> comment at the top of the file does.
	/// </remarks>
	/// <param name="tree">The syntax tree.</param>
	/// <param name="optionsProvider">The analyzer config options.</param>
	/// <returns><see langword="true"/> when the file is generated code.</returns>
	internal static bool IsGenerated(SyntaxTree tree, AnalyzerConfigOptionsProvider optionsProvider)
	{
		if (optionsProvider.GetOptions(tree).TryGetValue("generated_code", out string? generated))
		{
			if (string.Equals(generated, "true", StringComparison.OrdinalIgnoreCase))
			{
				return true;
			}

			if (string.Equals(generated, "false", StringComparison.OrdinalIgnoreCase))
			{
				return false;
			}
		}

		return HasGeneratedFileName(tree.FilePath) || HasAutoGeneratedHeader(tree);
	}

	private static bool HasGeneratedFileName(string filePath)
	{
		if (string.IsNullOrEmpty(filePath))
		{
			return false;
		}

		string fileName = Path.GetFileName(filePath);
		if (fileName.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase))
		{
			return true;
		}

		string name = Path.GetFileNameWithoutExtension(fileName);
		return name.EndsWith(".designer", StringComparison.OrdinalIgnoreCase)
			|| name.EndsWith(".generated", StringComparison.OrdinalIgnoreCase)
			|| name.EndsWith(".g", StringComparison.OrdinalIgnoreCase)
			|| name.EndsWith(".g.i", StringComparison.OrdinalIgnoreCase);
	}

	private static bool HasAutoGeneratedHeader(SyntaxTree tree) =>
		tree.GetRoot().GetFirstToken(includeZeroWidth: true).LeadingTrivia
			.Select(trivia => trivia.ToString())
			.Any(text =>
				(text.StartsWith("//", StringComparison.Ordinal) || text.StartsWith("/*", StringComparison.Ordinal))
				&& (text.IndexOf("<auto-generated", StringComparison.OrdinalIgnoreCase) >= 0
					|| text.IndexOf("<autogenerated", StringComparison.OrdinalIgnoreCase) >= 0));

	/// <summary>
	/// Determines whether a source file belongs to the project rather than to a package or the
	/// intermediate output.
	/// </summary>
	/// <param name="filePath">The source file path.</param>
	/// <param name="projectDir">The project directory, with a trailing separator.</param>
	/// <returns><see langword="true"/> when the file is project-owned source.</returns>
	private static bool IsProjectOwned(string filePath, string projectDir)
	{
		if (string.IsNullOrEmpty(filePath) ||
			!filePath.StartsWith(projectDir, StringComparison.OrdinalIgnoreCase))
		{
			return false;
		}

		string relative = filePath.Substring(projectDir.Length);

		return !relative.StartsWith("obj" + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)
			&& !relative.StartsWith("obj/", StringComparison.OrdinalIgnoreCase);
	}
}
